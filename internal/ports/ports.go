// ErrBusClosed is returned when publishing to a closed event bus.
var ErrBusClosed = errors.New("event bus is closed")

// EventMessage is one event published on the event bus. Key is used for
// partition affinity (Kafka-style): all messages with the same key are
// delivered in order to the same partition.
type EventMessage struct {
	Topic   string
	Key     string
	Payload []byte
	Headers map[string]string
}

// EventHandler processes a single event message. It must be idempotent:
// at-least-once delivery means it can be invoked again after a crash.
type EventHandler func(context.Context, EventMessage) error

// EventBus is the Phase 3 event backbone. Every published message must be
// delivered at least once to every consumer group subscribed to its topic.
type EventBus interface {
	Publish(ctx context.Context, msg EventMessage) error
	// Subscribe registers a consumer-group handler for a topic. It starts
	// delivery in the background and keeps delivering until ctx is cancelled.
	Subscribe(ctx context.Context, topic, group string, handler EventHandler) error
	Close() error
}

// ImageReader extracts text from an image. Implementations should handle
// photos of documents (NIN/BVN slips, transfer receipts) and return the
// readable text content.
type ImageReader interface {
	ReadImage(ctx context.Context, imageData []byte, mimeType string, prompt string) (string, error)
}

// SpeechToText transcribes audio bytes into text. Implementations should
// support common voice-note formats (OGG/Opus, MP3, WAV).
type SpeechToText interface {
	Transcribe(ctx context.Context, audioData []byte, mimeType string, language string) (string, error)
}

// MediaDownloader fetches the raw bytes of an inbound chat media message
// through the channel provider. The returned MIME type may be empty to fall
// back to the enqueued metadata; implementations must bound the download and
// surface per-provider errors so the conversation service can degrade.
type MediaDownloader interface {
	Download(ctx context.Context, channel, mediaID, mediaURL string) ([]byte, string, error)
}

// ChatAI classifies free-text input into FSM intents and generates
// conversational responses. Implementations must be stateless and fast.
type ChatAI interface {
	// ClassifyIntent maps a user message to one of the known FSM intents.
	// Returns the intent name, extracted entities, and a confidence score.
	ClassifyIntent(ctx context.Context, userMessage string, contextLines []string) (IntentResult, error)
	// Answer generates a conversational response to a question.
	Answer(ctx context.Context, question string, contextLines []string) (string, error)
}

// IntentResult is the outcome of an AI intent classification.
type IntentResult struct {
	Intent     string            `json:"intent"`
	Entities   map[string]string `json:"entities,omitempty"`
	Confidence float64           `json:"confidence"`
}
