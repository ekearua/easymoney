// Package ports declares external service boundaries used by the application.
package ports

import (
	"context"
	"encoding/json"
	"errors"
	"time"
)

// InitializePayment contains provider-neutral checkout initialization data.
type InitializePayment struct {
	Reference   string
	Email       string
	AmountKobo  int64
	Currency    string
	CallbackURL string
	Metadata    map[string]string
}

// Checkout is returned by a gateway after it creates a hosted checkout.
type Checkout struct {
	Reference string
	URL       string
}

// Verification is the normalized result of a server-side gateway verification.
type Verification struct {
	Reference  string
	Status     string
	AmountKobo int64
	Currency   string
	Domain     string
	Channel    string
	Metadata   map[string]string
	PaidAt     *time.Time
	Message    string
}

// GatewayWebhook is a validated and normalized payment provider event.
type GatewayWebhook struct {
	Event     string
	Reference string
	Raw       json.RawMessage
}

// PaymentGateway isolates the domain from a specific payment provider.
type PaymentGateway interface {
	Initialize(context.Context, InitializePayment) (Checkout, error)
	Verify(context.Context, string, int64) (Verification, error)
	ValidateWebhook(body []byte, signature string) (GatewayWebhook, error)
}

// TransferInstruction is a dynamic virtual account (DVA) generated by the
// gateway so a customer can pay by bank transfer.
type TransferInstruction struct {
	AccountNumber string
	AccountName   string
	BankName      string
	Reference     string // gateway-side reference to requery for completion
	ExpiresAt     time.Time
	ValidityMins  int
}

// TransferGateway is implemented by gateways that can generate dynamic virtual
// accounts for bank-transfer collection (Interswitch DVA).
type TransferGateway interface {
	Transfer(context.Context, InitializePayment) (TransferInstruction, error)
}

// InteractiveMessage describes a message with reply buttons or a list.
type InteractiveMessage struct {
	To          string
	Body        string
	ButtonLabel string
	Sections    []InteractiveSection
	Buttons     []InteractiveButton
}

// InteractiveSection groups options in a WhatsApp list.
type InteractiveSection struct {
	Title string
	Rows  []InteractiveRow
}

// InteractiveRow is one selectable WhatsApp list item.
type InteractiveRow struct {
	ID          string
	Title       string
	Description string
}

// InteractiveButton is one WhatsApp reply button.
type InteractiveButton struct {
	ID    string
	Title string
}

// Messenger isolates conversation behavior from WhatsApp's wire format.
type Messenger interface {
	SendText(context.Context, string, string) error
	SendInteractive(context.Context, InteractiveMessage) error
	SendCheckout(context.Context, string, string, string) error
	// SendLink sends a call-to-action URL message with a custom button label.
	// Web flows use it for the single link message that starts a browser flow.
	SendLink(context.Context, string, string, string, string) error
	SendTemplate(context.Context, string, string, []string) error
	SendImage(ctx context.Context, to string, imageData []byte, caption string) error
}

// EmailSender sends transactional onboarding and receipt email messages.
type EmailSender interface {
	Send(context.Context, string, string, string) error
}

// SMSSender sends an outbound SMS message and returns the provider's message
// identifier so a delivery-status webhook can correlate async callbacks. The
// empty string is returned when the provider does not expose an identifier.
type SMSSender interface {
	Send(ctx context.Context, to, body string) (string, error)
}

